using System;
using System.Collections.Generic;
using System.ComponentModel;
using System.IO;
using System.Net.Sockets;

namespace Emby.Okuzukey.Helpers
{
    /// <summary>
    /// Turns an exception into a short English description for log entries and dashboard
    /// messages.
    /// </summary>
    /// <remarks>
    /// Messages of exceptions that originate in the operating system (socket errors, Win32 file
    /// system errors) are localized by Windows into the system language, e.g. "Es konnte keine
    /// Verbindung hergestellt werden, da der Zielcomputer die Verbindung verweigerte." on a German
    /// system, and ended up verbatim in the plugin's log lines. Messages generated by .NET itself
    /// are English. Such OS errors are therefore described from their error code instead of their
    /// message, so every log line of this plugin is English regardless of the server's language.
    /// </remarks>
    internal static class ExceptionText
    {
        private static readonly Dictionary<SocketError, string> SocketErrors = new Dictionary<SocketError, string>
        {
            { SocketError.ConnectionRefused, "connection refused - the server is not listening on that port" },
            { SocketError.HostNotFound, "host not found" },
            { SocketError.TryAgain, "host name lookup failed" },
            { SocketError.NoData, "host name has no address" },
            { SocketError.NetworkUnreachable, "network unreachable" },
            { SocketError.NetworkDown, "network is down" },
            { SocketError.HostUnreachable, "host unreachable" },
            { SocketError.HostDown, "host is down" },
            { SocketError.TimedOut, "connection timed out" },
            { SocketError.ConnectionReset, "connection reset by the server" },
            { SocketError.ConnectionAborted, "connection aborted" },
            { SocketError.AddressNotAvailable, "address not available" },
            { SocketError.AccessDenied, "access denied" }
        };

        private static readonly Dictionary<int, string> Win32Errors = new Dictionary<int, string>
        {
            { 2, "file not found" },
            { 3, "path not found" },
            { 5, "access denied" },
            { 15, "drive not found" },
            { 21, "device not ready" },
            { 32, "file is in use by another process" },
            { 33, "part of the file is locked by another process" },
            { 39, "disk full" },
            { 53, "network path not found" },
            { 59, "unexpected network error" },
            { 64, "network name is no longer available" },
            { 67, "network name not found" },
            { 112, "disk full" },
            { 1231, "network location unreachable" }
        };

        /// <summary>
        /// English one-line description of <paramref name="exception"/>: the mapped OS error if
        /// the exception chain contains one (plus the file name, if known), otherwise the .NET
        /// message, which is English.
        /// </summary>
        public static string Describe(Exception exception)
        {
            if (exception == null)
            {
                return "unknown error";
            }

            for (var current = exception; current != null; current = current.InnerException)
            {
                var osText = DescribeOsError(current);
                if (osText != null)
                {
                    return AppendFileName(osText, exception);
                }
            }

            return exception.Message;
        }

        /// <summary>
        /// <c>true</c> if any exception in the chain carries an OS-localized message, i.e. its
        /// full text (as written by <c>ILogger.ErrorException</c>) may not be English.
        /// </summary>
        public static bool ContainsOsLocalizedMessage(Exception exception)
        {
            for (var current = exception; current != null; current = current.InnerException)
            {
                if (DescribeOsError(current) != null)
                {
                    return true;
                }
            }

            return false;
        }

        private static string DescribeOsError(Exception exception)
        {
            if (exception is SocketException socketException)
            {
                return SocketErrors.TryGetValue(socketException.SocketErrorCode, out var text)
                    ? text
                    : "socket error " + socketException.SocketErrorCode;
            }

            if (exception is Win32Exception win32Exception)
            {
                return DescribeWin32(win32Exception.NativeErrorCode);
            }

            // HRESULT facility 7 (FACILITY_WIN32): an I/O error whose message may come from Windows.
            if (exception is IOException && ((uint)exception.HResult & 0xFFFF0000u) == 0x80070000u)
            {
                return DescribeWin32(exception.HResult & 0xFFFF);
            }

            return null;
        }

        private static string DescribeWin32(int code)
        {
            return Win32Errors.TryGetValue(code, out var text) ? text : "system error " + code;
        }

        private static string AppendFileName(string text, Exception exception)
        {
            string fileName = null;
            if (exception is FileNotFoundException fileNotFound)
            {
                fileName = fileNotFound.FileName;
            }
            else if (exception is FileLoadException fileLoad)
            {
                fileName = fileLoad.FileName;
            }

            return string.IsNullOrEmpty(fileName) ? text : text + " ('" + fileName + "')";
        }
    }
}
